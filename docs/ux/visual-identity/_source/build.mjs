// Builds the concept SVGs and the asset list read by the review page.
// Usage (from the repository root): node docs/ux/visual-identity/_source/build.mjs [concept...]
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FILES = {
  identity: "00-identity.svg",
  landing: "01-landing.svg",
  discovery: "02-discovery.svg",
  comparison: "03-comparison.svg",
  charging: "04-charging.svg",
};
const ALL = [
  "tavola",
  "livrea",
  "notturno",
  "livrea-refined",
  "livrea-expressive",
  "livrea-consolidated",
];

const only = process.argv.slice(2);
for (const id of ALL) {
  if (only.length && !only.includes(id)) continue;
  if (!existsSync(join(root, "_source", `${id}.mjs`))) continue;
  const concept = (await import(`./${id}.mjs`)).default;
  mkdirSync(join(root, id), { recursive: true });
  for (const [screen, file] of Object.entries(FILES)) {
    writeFileSync(join(root, id, file), concept.screens[screen]());
    console.log(`${id}/${file}`);
  }
}

// Content hashes let the review page bypass the browser cache after every rebuild.
const hashes = {};
for (const id of ALL) {
  for (const file of Object.values(FILES)) {
    const path = join(root, id, file);
    if (existsSync(path))
      hashes[`${id}/${file}`] = createHash("sha256")
        .update(readFileSync(path))
        .digest("hex")
        .slice(0, 10);
  }
}
// Written in Prettier's format so that `npm run format:check` stays clean after a build.
const entries = Object.entries(hashes).map(([k, v]) => `  "${k}": "${v}",\n`);
writeFileSync(
  join(root, "review", "assets.js"),
  `// Generated by _source/build.mjs. Do not edit.\nwindow.VI_ASSETS = {\n${entries.join("")}};\n`,
);
